#!/usr/bin/env node
/* Benny's Sphere Splash - build js/voice-lines.generated.js from content/voice-lines.json.
 *
 *   node tools/build-voice-lines.cjs
 *
 * content/ is the authoring source and stays off the site (.gitignore); the bundle
 * carries the same JSON byte for byte, so the source can be rebuilt from what ships.
 */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = path.join(root, 'content', 'voice-lines.json');
const out = path.join(root, 'js', 'voice-lines.generated.js');

const text = fs.readFileSync(src, 'utf8');
const data = JSON.parse(text);            // fail loudly on a broken file
const ids = new Set();
for (const [fam, lines] of Object.entries(data.families)) {
  for (const l of lines) {
    if (!l.id || !l.speaker || !l.text) throw new Error(fam + ': every line needs id, speaker and text');
    if (!data.speakers[l.speaker]) throw new Error(l.id + ': unknown speaker ' + l.speaker);
    if (ids.has(l.id)) throw new Error('duplicate line id ' + l.id);
    ids.add(l.id);
  }
}
// A line recorded in parts (line.parts, clip keys with {slots}) may name only line ids and pieces.
const pieces = data.pieces || {};
for (const [fam, lines] of Object.entries(data.families)) for (const l of lines) for (const part of l.parts || []) {
  const id = part.split('@')[0];
  if (!ids.has(id) && !pieces[id]) throw new Error(l.id + ': part ' + part + ' is not a line id or a piece');
}
for (const [id, pc] of Object.entries(pieces)) {
  if (id === '_') continue;
  if (!pc.text || !data.speakers[pc.speaker]) throw new Error('piece ' + id + ' needs text and a known speaker');
  if (ids.has(id)) throw new Error('piece ' + id + ' clashes with a line id');
}
fs.writeFileSync(out, '/* Generated by tools/build-voice-lines.cjs from content/voice-lines.json - edit that, not this. */\n' +
  'SS.VOICE_LINES = ' + text.trim() + ';\n');
console.log('wrote ' + path.relative(root, out) + ': ' + ids.size + ' lines in ' + Object.keys(data.families).length + ' families');
