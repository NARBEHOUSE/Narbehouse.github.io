// Builds js/model-data.js: the swimmer bodies and their animation clips, as base64 GLB
// strings the game hands to THREE.GLTFLoader.parse() - no fetch, so the game runs
// from file:// like the rest of the hub.
//
// Source: Quaternius "Universal Base Characters" + "Universal Animation Library"
// (Standard/free editions, CC0). Both share one 65-joint rig, so clips from the
// animation library drive the base characters by bone name.
//
// Textures are dropped on purpose: swimmers are flat toon colours set in code (kit,
// skin, hair), which is both lighter and easier for a low-vision player to read.
//
// Run from this folder:  npm run models -- <path to the unzipped Quaternius folder>
// (defaults to ../../../../../../../Assets/quaternius beside the repo)
import { NodeIO } from '@gltf-transform/core';
import { prune, dedup, resample } from '@gltf-transform/functions';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(process.argv[2] || path.join(here, '../../../../../../../Assets/quaternius'));
const out = path.resolve(here, '../../js/model-data.js');

const UBC = path.join(src, 'UBC_Standard/Universal Base Characters[Standard]/Base Characters/Godot - UE');
const UAL = path.join(src, 'UAL_Standard/Universal Animation Library[Standard]/Unreal-Godot/UAL1_Standard.glb');

// Clip name in the library -> the name the game uses.
const CLIPS = {
  Swim_Fwd_Loop: 'swim',
  Swim_Idle_Loop: 'tread',
  Punch_Jab: 'tackleA',
  Punch_Cross: 'tackleB',
  Spell_Simple_Shoot: 'throw',
  Hit_Chest: 'hitChest',
  Hit_Head: 'hitHead',
  Roll: 'roll',
  Dance_Loop: 'cheer',
  Jump_Start: 'leap',
};

const io = new NodeIO();

function stripTextures(doc) {
  for (const mat of doc.getRoot().listMaterials()) {
    mat.setBaseColorTexture(null).setNormalTexture(null)
      .setMetallicRoughnessTexture(null).setOcclusionTexture(null).setEmissiveTexture(null);
  }
  for (const tex of doc.getRoot().listTextures()) tex.dispose();
}

async function body(file) {
  // Read the JSON by hand and drop image references before loading: the free pack's
  // .gltf points at textures it does not ship (T_Hair_1_Normal_png.png), and none of
  // them are used anyway.
  const json = JSON.parse(fs.readFileSync(path.join(UBC, file), 'utf8'));
  delete json.images; delete json.textures; delete json.samplers;
  for (const m of json.materials || []) {
    delete m.normalTexture; delete m.occlusionTexture; delete m.emissiveTexture;
    if (m.pbrMetallicRoughness) { delete m.pbrMetallicRoughness.baseColorTexture; delete m.pbrMetallicRoughness.metallicRoughnessTexture; }
  }
  const resources = {};
  for (const b of json.buffers) resources[b.uri] = new Uint8Array(fs.readFileSync(path.join(UBC, decodeURIComponent(b.uri))));
  const doc = await io.readJSON({ json, resources });
  stripTextures(doc);
  await doc.transform(dedup(), prune());
  return Buffer.from(await io.writeBinary(doc));
}

async function clips() {
  const doc = await io.read(UAL);
  const root = doc.getRoot();
  for (const anim of root.listAnimations()) {
    const name = CLIPS[anim.getName()];
    if (name) { anim.setName(name); continue; }
    // Dispose the samplers and channels explicitly: disposing the animation alone leaves
    // them (and so their keyframe accessors) attached. Accessors are shared between
    // clips, so they are left for prune() rather than disposed here.
    for (const s of anim.listSamplers()) s.dispose();
    for (const c of anim.listChannels()) c.dispose();
    anim.dispose();
  }
  // The library ships a mannequin mesh; the game only wants the bone tracks.
  for (const node of root.listNodes()) { if (node.getMesh()) node.setMesh(null); if (node.getSkin()) node.setSkin(null); }
  for (const mesh of root.listMeshes()) mesh.dispose();
  for (const skin of root.listSkins()) skin.dispose();
  stripTextures(doc);
  await doc.transform(resample(), dedup(), prune({ keepLeaves: true }));
  const kept = root.listAnimations().map(a => a.getName()).sort();
  const missing = Object.values(CLIPS).filter(n => !kept.includes(n));
  if (missing.length) throw new Error('clips missing from the library: ' + missing.join(', '));
  return Buffer.from(await io.writeBinary(doc));
}

const parts = {
  male: await body('Superhero_Male_FullBody.gltf'),
  female: await body('Superhero_Female_FullBody.gltf'),
  clips: await clips(),
};

const lines = [
  '/* model-data.js - GENERATED by tools/build/prep-models.mjs; do not edit.',
  ' * Swimmer bodies and animation clips from Quaternius Universal Base Characters and',
  ' * Universal Animation Library (CC0 1.0, see CREDITS.txt), as base64 GLB. */',
  '(function () {',
  '  window.SS = window.SS || {};',
  '  SS.MODEL_DATA = {',
  ...Object.entries(parts).map(([k, b]) => `    ${k}: '${b.toString('base64')}',`),
  '  };',
  '})();',
  '',
];
fs.writeFileSync(out, lines.join('\n'));
for (const [k, b] of Object.entries(parts)) console.log(k.padEnd(7), (b.length / 1024).toFixed(0) + ' KB');
console.log('wrote', path.relative(process.cwd(), out), (fs.statSync(out).size / 1024).toFixed(0) + ' KB');
