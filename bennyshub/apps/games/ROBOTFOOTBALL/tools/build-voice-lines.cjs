#!/usr/bin/env node
/* ROBOTFOOTBALL — build js/voice-lines.generated.js from content/voice-lines.json.
 *
 *   node tools/build-voice-lines.cjs
 *
 * Checks the script (ids unique across lines and replies, speakers known, every family has a play rate,
 * {team} is the only slot) and writes the bundle the game loads as window.RF_VOICE_LINES. Review-only keys
 * (briefs, notes) stay in the bundle: they are small and keep the source rebuildable from what ships.
 * Also writes js/voice-index.generated.js from audio/vo/index.json (an empty list until recordings ship).
 */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = path.join(root, 'content', 'voice-lines.json');
const data = JSON.parse(fs.readFileSync(src, 'utf8'));            // fail loudly on a broken file

const ids = new Set(), problems = [];
const check = (l, fam) => {
  if (!l.id || !l.speaker || !l.text) problems.push(fam + ': every line needs id, speaker and text');
  if (!data.speakers[l.speaker]) problems.push(l.id + ': unknown speaker ' + l.speaker);
  if (ids.has(l.id)) problems.push('duplicate line id ' + l.id);
  ids.add(l.id);
  for (const m of l.text.matchAll(/\{(\w+)\}/g)) if (m[1] !== 'team') problems.push(l.id + ': unknown slot {' + m[1] + '}');
};
for (const [fam, lines] of Object.entries(data.families)) {
  for (const l of lines) { check(l, fam); if (l.reply) check(l.reply, fam); }
  const rate = (data.play || {})[fam] || (fam.startsWith('opp_') && (data.play || {}).opponent);
  if (!rate) problems.push(fam + ': no play rate in "play"');
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const bundle = {};
for (const k of ['speakers', 'play', 'families']) bundle[k] = data[k];
fs.writeFileSync(path.join(root, 'js', 'voice-lines.generated.js'),
  '/* Generated by tools/build-voice-lines.cjs from content/voice-lines.json - edit that, not this. */\n' +
  'window.RF_VOICE_LINES = ' + JSON.stringify(bundle) + ';\n');

const idxPath = path.join(root, 'audio', 'vo', 'index.json');
const index = fs.existsSync(idxPath) ? JSON.parse(fs.readFileSync(idxPath, 'utf8')) : { lines: {} };
fs.writeFileSync(path.join(root, 'js', 'voice-index.generated.js'),
  '/* Generated by tools/build-voice-lines.cjs from audio/vo/index.json - recordings by clip key. */\n' +
  'window.RF_VOICE_INDEX = ' + JSON.stringify({ lines: index.lines || {} }) + ';\n');
console.log('wrote js/voice-lines.generated.js: ' + ids.size + ' lines in ' + Object.keys(data.families).length +
  ' families; js/voice-index.generated.js: ' + Object.keys(index.lines || {}).length + ' recordings');
