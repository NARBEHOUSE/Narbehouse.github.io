const {chromium,expect}=require('@playwright/test');
const assert=require('node:assert/strict');
const path=require('node:path');
const base='http://127.0.0.1:4173', keyboard=base+'/bennyshub/apps/tools/keyboard/index.html';
let browser;
(async()=>{
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext(),page=await context.newPage(),errors=[],requests=[];
  page.on('pageerror',e=>errors.push(e.message));
  context.on('request',r=>requests.push({url:r.url(),method:r.method()}));
  await page.goto(base+'/bennyshub/index.html');
  await page.evaluate(()=>navigator.serviceWorker.ready);
  await page.goto(keyboard);
  await page.waitForFunction(()=>window.predictionSystem?.dataLoaded,{},{timeout:45000});
  const suggestions=await page.evaluate(async()=>({next:await predictionSystem.getLocalPredictions('I WOULD LIKE TO '),prefix:await predictionSystem.getLocalPredictions('I WANT TO DR')}));
  assert.equal(suggestions.next.filter(Boolean).length,6);
  assert.ok(suggestions.prefix.filter(Boolean).every(w=>w.startsWith('DR')));
  console.log('Original local suggestions:',suggestions);
  const regressions=await page.evaluate(async()=>({today:await predictionSystem.getLocalPredictions('how are you doing t'),help:await predictionSystem.getLocalPredictions('thank you for your h'),me:await predictionSystem.getLocalPredictions('can you help m')}));
  assert.ok(regressions.today.includes('TODAY'));assert.ok(regressions.help.includes('HELP'));assert.ok(regressions.me.includes('ME'));
  console.log('Local conversational regressions:',regressions);
  assert.equal((await page.evaluate(()=>predictionSystem.getLocalPredictions('HOW ARE ')))[0],'YOU');
  assert.equal((await page.evaluate(()=>predictionSystem.getLocalPredictions('I NEED ')))[0],'TO');

  await page.evaluate(()=>NarbeVoiceManager.updateSettings({ttsEnabled:false}));
  for(const char of 'HELLO')await page.locator('#keyboard').getByRole('button',{name:char,exact:true}).click();
  await expect(page.locator('#textBar')).toHaveText('HELLO|');
  await expect(page.locator('#predictBar').getByRole('button',{name:'HELLO',exact:true})).toHaveCount(0);
  await page.locator('#keyboard').getByRole('button',{name:/Space/}).click();
  await expect(page.locator('#predictBar').getByRole('button',{name:'HELLO',exact:true})).toHaveCount(0);
  await page.locator('#keyboard').getByRole('button',{name:/Clear/}).click();
  for(const char of 'I WANT TO DR')await page.locator('#keyboard').getByRole('button',{name:char===' '?/Space/:char,exact:char!==' '}).click();
  await expect(page.locator('#predictBar').getByRole('button',{name:'DRINK',exact:true})).toBeVisible();
  await page.locator('#predictBar').getByRole('button',{name:'DRINK',exact:true}).click();
  await expect(page.locator('#textBar')).toHaveText('I WANT TO DRINK |');
  await page.evaluate(()=>{predictionSystem.recordLocalWord('ZORBELL');predictionSystem.recordNgram('I WANT','ZORBELL');});
  assert.ok((await page.evaluate(()=>predictionSystem.getLocalPredictions('I WANT '))).slice(0,2).includes('ZORBELL'));
  await page.screenshot({path:path.resolve('artifacts/keyboard-local.png')});
  // The original dictionary and learned vocabulary remain available offline.
  await context.setOffline(true);await page.reload();
  await page.waitForFunction(()=>window.predictionSystem?.dataLoaded,{},{timeout:45000});
  assert.ok((await page.evaluate(()=>predictionSystem.getLocalPredictions('I WANT '))).includes('ZORBELL'));
  assert.ok((await page.evaluate(()=>predictionSystem.getLocalPredictions('how are you doing t'))).includes('TODAY'));
  assert.equal(await page.evaluate(()=>typeof window.kenLMPredictor),'undefined');
  assert.ok(requests.every(r=>r.method==='GET'&&new URL(r.url).origin===base));
  assert.ok(!requests.some(r=>/kenlm/i.test(r.url)));
  assert.deepEqual(errors,[]);
  console.log('Keyboard passed: original local suggestions, no completed-word repeat, typing/selecting suggestions, learned vocabulary, offline reload, no KenLM/model requests or typed-text requests.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>browser?.close());
