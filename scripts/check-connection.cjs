const {chromium, expect}=require('@playwright/test');
const path=require('node:path'),fs=require('node:fs/promises');
const root=path.resolve(__dirname,'..'),base=process.env.HUB_TEST_ORIGIN||'http://127.0.0.1:4173';
let browser,context;
(async()=>{
  const artifacts=path.join(root,'artifacts');await fs.mkdir(artifacts,{recursive:true});
  browser=await chromium.launch({headless:true});
  const plain=await browser.newPage();
  // Test profile writes must not trigger the IDE's whole-workspace live reload.
  const suppressPreviewReload=route=>route.fulfill({contentType:'application/javascript',body:''});
  await plain.route('**/___vscode_livepreview_injected_script',suppressPreviewReload);
  await plain.goto(base+'/bennyshub/index.html');
  await plain.locator('#modal-cancel').click();await plain.locator('#hub-settings summary').click();
  await expect(plain.locator('#extension-status')).toHaveText('Not connected');
  await expect(plain.locator('#extension-status')).toHaveAttribute('data-connection','disconnected');
  await plain.locator('#extension-recheck').click();
  await expect(plain.locator('#extension-recheck')).toBeDisabled();
  await expect(plain.locator('#extension-status')).toHaveText('Checking…');
  await expect(plain.locator('#extension-status')).toHaveText('Not connected');
  await expect(plain.locator('#extension-recheck')).toBeEnabled();
  await plain.screenshot({path:path.join(artifacts,'connection-disconnected.png')});
  await plain.goto(base+'/bennyshub/extension-setup.html');
  await plain.locator('#settings').click();await expect(plain.locator('#settings')).toHaveText(/Opening settings/);
  await expect(plain.locator('#setup-error')).toContainText('Companion did not respond.',{timeout:6000});
  await expect(plain.locator('#settings')).toBeEnabled();
  await browser.close();browser=null;
  const extension=path.join(root,'extension');
  context=await chromium.launchPersistentContext(path.join(artifacts,'connection-profile-'+Date.now()),{channel:'chromium',headless:true,args:['--disable-extensions-except='+extension,'--load-extension='+extension]});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/___vscode_livepreview_injected_script',suppressPreviewReload);
  await page.goto(base+'/bennyshub/index.html');await page.locator('#modal-cancel').click();
  await page.locator('#hub-settings summary').click();
  await expect(page.locator('#extension-status')).toHaveText('Connected',{timeout:15000});
  await expect(page.locator('#extension-status')).toHaveAttribute('data-connection','connected');
  await expect.poll(()=>page.evaluate(()=>BennyExtension.state.version)).toBe(JSON.parse(await fs.readFile(path.join(extension,'manifest.json'))).version);
  await page.locator('#extension-recheck').click();await expect(page.locator('#extension-recheck')).toBeEnabled();
  await expect(page.locator('#extension-status')).toHaveText('Connected');
  await page.screenshot({path:path.join(artifacts,'connection-connected.png')});
  await page.locator('#hub-settings summary').click();
  await page.locator('[data-target="tools"]').first().click();await expect(page.locator('#tools-grid .app-btn')).toHaveCount(6);
  await page.locator('#tools-grid [data-title="Streaming"]').click();
  const streaming=page.frameLocator('#app-iframe');
  await expect(streaming.locator('#main-menu .menu-btn')).toHaveCount(7);
  await expect(streaming.locator('#companion-required[open]')).toHaveCount(0);
  await streaming.locator('#btn-browse').click();await expect(streaming.locator('#items-grid .card-image').first()).toBeVisible();
  await page.screenshot({path:path.join(artifacts,'streaming-in-hub.png')});
  await page.goto(base+'/bennyshub/extension-setup.html');await expect(page.locator('#status')).toHaveText('Connected');
  await page.locator('#check').click();await expect(page.locator('#check')).toBeEnabled();await expect(page.locator('#status')).toHaveText('Connected');
  const opened=context.waitForEvent('page');await page.locator('#settings').click();const options=await opened;
  await options.waitForURL('chrome-extension://*/options.html');await expect(options.locator('h1')).toBeVisible();
  await expect(page.locator('#settings')).toBeEnabled();await expect(page.locator('#setup-error')).toBeHidden();
  expect(errors).toEqual([]);
  console.log('Connection checks passed at '+base+': connected/disconnected labels, retry feedback, setup page and six Tools cards.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{await context?.close();await browser?.close();});
