// Compile the existing keyboard dictionary into a small, deterministic read-only index.
// No personal browser history, timestamps, API, or model download is included.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=JSON.parse(fs.readFileSync(path.join(root,'bennyshub/apps/tools/keyboard/web_keyboard_predictions.json'),'utf8'));
const token=value=>value.toLowerCase().replace(/[’]/g,"'");
const valid=value=>/^[\p{L}]+(?:['-][\p{L}]+)*$/u.test(value);
const vocabulary=Object.entries(source.frequent_words).map(([word,data])=>[token(word),Math.round(Math.log2(1+Math.max(0,data.count)))]).filter(([word])=>valid(word));
const following=new Map();
function add(context,next,weight){if(!following.has(context))following.set(context,new Map());const candidates=following.get(context);candidates.set(next,Math.max(candidates.get(next)||0,weight));}
for(const [key,data] of [...Object.entries(source.bigrams),...Object.entries(source.trigrams)]){
  const words=token(key).split(/\s+/);if(!words.every(valid))continue;
  const weight=Math.round(Math.log2(1+Math.max(0,data.count))*1000)/1000;
  add(words.slice(0,-1).join(' '),words.at(-1),weight);
  // Preserve phrase continuations too ("how" -> "are you"). Filter by each board at runtime.
  if(words.length===3)add(words[0],words.slice(1).join(' '),weight);
}
const contexts=Object.fromEntries([...following].sort(([a],[b])=>a.localeCompare(b)).map(([key,candidates])=>[key,[...candidates].sort((a,b)=>b[1]-a[1]||a[0].localeCompare(b[0]))]));
const data={version:2,source:'Existing Benny’s Hub keyboard dictionary; counts only',vocabulary:Object.fromEntries(vocabulary),contexts};
const text='/* Generated by scripts/build-phrase-predictions.cjs. Do not edit by hand. */\n(function(root){const data='+JSON.stringify(data)+';if(typeof module==="object"&&module.exports)module.exports=data;else root.PhrasePredictionData=data;})(globalThis);\n';
fs.writeFileSync(path.join(root,'bennyshub/apps/tools/phraseboard/prediction-data.js'),text);
console.log(JSON.stringify({words:vocabulary.length,contexts:following.size,bytes:Buffer.byteLength(text)}));
