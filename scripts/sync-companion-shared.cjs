// Keep Companion policy and validation byte-for-byte identical to the shared web helpers.
// Run without arguments to synchronize, or --check to fail on missing/stale copies.
const fs = require('node:fs/promises');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = ['choice-scan.js', 'voice-manager.js', 'scan-status-badge.js', 'scan-status-badge.css', 'data-backup.js'];
const checkOnly = process.argv.includes('--check');
async function regularFile(file) {
  const info = await fs.lstat(file);
  if (!info.isFile() || info.isSymbolicLink()) throw Error('Expected a regular file: ' + path.relative(root, file));
}
async function safeDirectory(directory, create) {
  const relative = path.relative(root, directory);
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) throw Error('Unsafe shared-assets directory');
  let current = root;
  for (const part of relative.split(path.sep)) {
    current = path.join(current, part);
    if (create) await fs.mkdir(current).catch(error => { if (error.code !== 'EEXIST') throw error; });
    const info = await fs.lstat(current);
    if (!info.isDirectory() || info.isSymbolicLink()) throw Error('Unsafe shared-assets directory: ' + path.relative(root, current));
  }
}
async function synchronize(to, expected) {
  const name = path.basename(to);
  const existing = await fs.lstat(to).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  if (existing && (!existing.isFile() || existing.isSymbolicLink())) throw Error('Unsafe shared asset: ' + name);
  if (checkOnly) {
    if (!existing || !expected.equals(await fs.readFile(to))) {
      throw Error('Companion shared asset is missing or stale: ' + name + '. Run node scripts/sync-companion-shared.cjs first.');
    }
  } else {
    await fs.writeFile(to, expected);
  }
}
(async () => {
  const source = path.join(root, 'bennyshub', 'shared');
  const destination = path.join(root, 'extension', 'shared');
  await safeDirectory(source, false);
  await safeDirectory(destination, !checkOnly);
  let badgeCSS;
  for (const name of files) {
    const from = path.join(source, name), to = path.join(destination, name);
    await regularFile(from);
    const expected = await fs.readFile(from);
    await synchronize(to, expected);
    if (name === 'scan-status-badge.css') badgeCSS = expected.toString('utf8');
  }
  // Content scripts cannot style a closed shadow root with document CSS.
  // Bundle the canonical text as data so the platform can insert it there.
  const styleModule = '// Generated by scripts/sync-companion-shared.cjs; do not edit.\n' +
    'globalThis.BennyScanBadgeCSS = ' + JSON.stringify(badgeCSS) + ';\n';
  await synchronize(path.join(destination, 'scan-status-badge-style.js'), Buffer.from(styleModule));
  console.log('Companion shared assets ' + (checkOnly ? 'match' : 'synchronized with') + ' bennyshub/shared (5 exact copies and generated badge CSS text).');
})().catch(error => { console.error(error.message); process.exitCode = 1; });
